HEX_RE = re.compile(r"^#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$")


def fmt_num(v):
    """数字格式化：int 原样；float 去尾零（1.0 → '1.0'，0.50 → '0.5'）。"""
    if isinstance(v, bool):
        raise TypeError("bool 不是合法 token 值")
    if isinstance(v, int):
        return str(v)
    s = repr(float(v))
    return s


def classify(group, key, value):
    """叶子值分类 → (kind, …)。kind ∈ size|int|ms|float|color|weight|skip|nested|array"""
    if key.startswith("_"):
        return ("skip",)
    if (group, key) in SKIP_KEYS:
        return ("skip",)
    if isinstance(value, dict):
        return ("nested", value)
    if isinstance(value, list):
        return ("array", value)
    if isinstance(value, str):
        if HEX_RE.match(value):
            return ("color", value)
        if key.endswith("Weight") and value in SWIFT_WEIGHTS:
            return ("weight", value)
        return ("skip",)  # 语义引用（primary/surfaceVariant/capsule/easing 等），不进代码常量
    if isinstance(value, (int, float)):
        if key in INT_KEYS:
            return ("int", value)
        if key.endswith("Ms"):
            return ("ms", value)
        if isinstance(value, float) and any(t in key.lower() for t in ("alpha", "ratio", "scale")):
            return ("float", value)
        return ("size", value)
    return ("skip",)


def flatten(group, data):
    """把 group dict 拍平成 [(name, kind, value)]。嵌套 dict 按 parentKey+Child 展开一层。"""
    out = []
    for key, value in data.items():
        kind, *rest = classify(group, key, value)
        if kind == "nested":
            for child_key, child_value in rest[0].items():
                if child_key.startswith("_"):
                    continue
                ck = key + child_key[0].upper() + child_key[1:]
                ckind, *crest = classify(group, ck, child_value)
                if ckind in ("size", "int", "ms", "float", "color", "weight"):
                    out.append((ck, ckind, crest[0]))
        elif kind in ("size", "int", "ms", "float", "color", "weight", "array"):
            out.append((key, kind, rest[0] if rest else None))
    return out


def parse_hex(hex_str):
    """#AARRGGBB / #RRGGBB → (r, g, b, a) 0-1 浮点。"""
    h = hex_str.lstrip("#")
    if len(h) == 6:
        h = "FF" + h
    a = int(h[0:2], 16) / 255
    r = int(h[2:4], 16) / 255
    g = int(h[4:6], 16) / 255
    b = int(h[6:8], 16) / 255
    return r, g, b, a


def swift_color(hex_str):
    r, g, b, a = parse_hex(hex_str)
    if a != 1.0:
        return f'Color(hex: "{hex_str.lstrip("#")}")'
    if (r, g, b) == (1.0, 1.0, 1.0):
        return "Color.white"
    if (r, g, b) == (0.0, 0.0, 0.0):
        return "Color.black"
    return f'Color(hex: "{hex_str.lstrip("#")}")'


def kotlin_color(hex_str):
    r, g, b, a = parse_hex(hex_str)
    if a != 1.0:
        return f"Color(0x{hex_str.lstrip('#')})"
    if (r, g, b) == (1.0, 1.0, 1.0):
        return "Color.White"
    if (r, g, b) == (0.0, 0.0, 0.0):
        return "Color.Black"
    return f"Color(0x{hex_str.lstrip('#')})"


def gradient_swift(stops):
    """gradientStops: ["transparent", "black@0.55"] → SwiftUI Color 数组行。"""
    items = []
    for s in stops:
        if s == "transparent":
            items.append("Color.clear")
        elif "@" in s:
            base, alpha = s.split("@", 1)
            items.append(f"Color.{base}.opacity({alpha})")
        else:
            items.append(f"Color.{s}")
    return items


def gradient_kotlin(stops):
    items = []
    for s in stops:
        if s == "transparent":
            items.append("Color.Transparent")
        elif "@" in s:
            base, alpha = s.split("@", 1)
            items.append(f"Color.{base.capitalize()}.copy(alpha = {alpha}f)")
        else:
            items.append(f"Color.{base.capitalize()}")
    return items


