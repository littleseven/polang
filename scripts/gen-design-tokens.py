def gen_swift(tokens):
    parts = [
        "import SwiftUI",
        "import Foundation",
        "",
        f"// MARK: - Design Tokens（{GENERATED_BANNER}）",
        "//",
        "// SSOT: shared/src/commonMain/resources/design-tokens.json",
        "// 所有新增 UI 必须引用这些常量，禁止硬编码尺寸/颜色/圆角。",
        "// 完整提取方法学/漂移记录/内容色板见 docs/03-TECHNICAL-SPECS/DESIGN_TOKENS_SPEC.md。",
    ]
    for group in IOS_ORDER:
        data = tokens[group]
        parts += ["", f"// MARK: - {MARK_NAMES[group]}", ""]
        if group == "typography":
            parts.append(swift_typography(data))
        elif group == "colorScheme":
            parts.append(swift_color_scheme(data))
            parts += [
                "",
                "// MARK: - Scheme 解析（跨屏共享）",
                "",
                "/// 按当前主题取 M3 语义色组。用法：`@Environment(\\.colorScheme)` + `let s = appScheme(cs)`。",
                "/// 各屏统一经此消费语义色，禁止硬编码 Color.white/opacity 近似（[PARITY] 契约色以 design-tokens.json 为准）。",
                "func appScheme(_ cs: ColorScheme) -> SchemeColors {",
                "    cs == .dark ? AppColorScheme.dark : AppColorScheme.light",
                "}",
            ]
        elif group == "motion":
            parts.append(swift_motion(data))
        elif group == "radius":
            parts.append(swift_simple_enum(group, data))
            parts += [
                "",
                "enum AppShapes {",
            ]
            for key, value in data.items():
                if key.startswith("_"):
                    continue
                parts.append(f"    static let {key} = RoundedRectangle(cornerRadius: AppRadius.{key}, style: .continuous)")
            parts.append("}")
        else:
            parts.append(swift_simple_enum(group, data))
    parts += [
        "",
        "// MARK: - Color(hex:) 工具（ARGB 十六进制，与 JSON 一致）",
        "",
        "private extension Color {",
        "    init(hex: String) {",
        "        let scanner = Scanner(string: hex)",
        "        var hexNumber: UInt64 = 0",
        "        scanner.scanHexInt64(&hexNumber)",
        "        let a = Double((hexNumber & 0xFF00_0000) >> 24) / 255",
        "        let r = Double((hexNumber & 0x00FF_0000) >> 16) / 255",
        "        let g = Double((hexNumber & 0x0000_FF00) >> 8) / 255",
        "        let b = Double(hexNumber & 0x0000_00FF) / 255",
        "        self.init(.sRGB, red: r, green: g, blue: b, opacity: a)",
        "    }",
        "}",
        "",
    ]
    return "\n".join(parts)


