def collect_outputs(tokens):
    return {
        IOS_OUT: gen_swift(tokens),
        ANDROID_DS / "Spacing.kt": gen_kotlin_spacing(tokens),
        ANDROID_DS / "AppShapes.kt": gen_kotlin_shapes(tokens),
        ANDROID_DS / "Color.kt": gen_kotlin_color(tokens),
        ANDROID_DS / "Typography.kt": gen_kotlin_typography(tokens),
        ANDROID_DS / "DesignTokens.kt": gen_kotlin_tokens(tokens),
        ARDOT_OUT: json.dumps(gen_ardot_payload(tokens), ensure_ascii=False, indent=2) + "\n",
    }


def main():
    check_mode = "--check" in sys.argv
    tokens = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    outputs = collect_outputs(tokens)

    if check_mode:
        stale = []
        for path, content in outputs.items():
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
        if stale:
            print("❌ 生成物与 design-tokens.json 不一致（禁止手改生成物；改 JSON 后重跑生成器）：")
            for path in stale:
                print(f"   - {path.relative_to(PROJECT_ROOT)}")
                if path.exists():
                    diff = difflib.unified_diff(
                        path.read_text(encoding="utf-8").splitlines(),
                        outputs[path].splitlines(),
                        fromfile="磁盘", tofile="重新生成", lineterm="")
                    print("\n".join(list(diff)[:40]))
            sys.exit(1)
        print(f"✅ design-tokens 生成物与 SSOT 一致（{len(outputs)} 个文件）")
        return

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"写入 {path.relative_to(PROJECT_ROOT)}")
    print("完成。iOS/Android 镜像 + Ardot payload 已同步。")


if __name__ == "__main__":
    main()
