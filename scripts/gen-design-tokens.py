def swift_prop_line(group, name, kind, value):
    if kind == "size":
        return f"    static let {name}: CGFloat = {fmt_num(value)}"
    if kind == "int":
        return f"    static let {name}: Int = {fmt_num(value)}"
    if kind == "ms":
        return f"    static let {name}: Double = {fmt_num(value)}"
    if kind == "float":
        if (group, name) in SWIFT_CG_FLOAT_KEYS:
            return f"    static let {name}: CGFloat = {fmt_num(value)}"
        return f"    static let {name}: Double = {fmt_num(value)}"
    if kind == "color":
        return f"    static let {name} = {swift_color(value)}"
    if kind == "weight":
        return f"    static let {name}: Font.Weight = {SWIFT_WEIGHTS[value]}"
    if kind == "array":  # 目前仅 gradientStops
        items = gradient_swift(value)
        body = "\n".join(f"        {it}," for it in items).rstrip(",")
        return f"    static let {name}: [Color] = [\n{body}\n    ]"
    raise ValueError(f"未知 kind: {kind}")


def swift_simple_enum(group, data):
    lines = [f"enum {ENUM_NAMES[group]} {{"]
    for name, kind, value in flatten(group, data):
        lines.append(swift_prop_line(group, name, kind, value))
    for (raw_group, _key), raw_line in RAW_SWIFT_VALUES.items():
        if raw_group == group:
            lines.append(f"    {raw_line}")
    lines.append("}")
    return "\n".join(lines)


def swift_typography(data):
    roles = [(k, v) for k, v in data.items() if not k.startswith("_")]
    lines = [
        "/// 字号角色。`font` 直接产出 SwiftUI Font；`lineHeight`/`letterSpacing` 供 `.lineSpacing`/`.tracking` 使用。",
        "struct TypeStyle {",
        "    let size: CGFloat",
        "    let lineHeight: CGFloat",
        "    let weight: Font.Weight",
        "    let letterSpacing: CGFloat",
        "",
        "    var font: Font { .system(size: size, weight: weight) }",
        "}",
        "",
        "enum AppTypography {",
    ]
    for role, spec in roles:
        lines.append(
            f"    static let {role} = TypeStyle(size: {fmt_num(spec['size'])}, "
            f"lineHeight: {fmt_num(spec['lineHeight'])}, weight: {SWIFT_WEIGHTS[spec['weight']]}, "
            f"letterSpacing: {fmt_num(spec['letterSpacing'])})"
        )
    lines += [
        "",
        "    /// 内联字重覆盖（Android 在 M3 role 之上叠加：模型卡名 SemiBold、必备徽章 Bold 等）。",
        "    enum WeightOverride {",
        "        static let semibold: Font.Weight = .semibold",
        "        static let bold: Font.Weight = .bold",
        "    }",
        "}",
    ]
    return "\n".join(lines)


def swift_color_scheme(data):
    light = data["light"]
    dark = data["dark"]
    keys = list(light.keys())
    lines = [
        "/// 一组随主题切换的语义色。Android 12+ 走 Material You 动态取色，iOS 无等价物，统一用此基准。",
        "/// 已修正 Android 端两处 bug：ErrorLight alpha=00 透明、Dark tertiaryContainer 误指 TertiaryDark。",
        "struct SchemeColors {",
    ]
    lines += [f"    let {k}: Color" for k in keys]
    lines += ["}", "", "enum AppColorScheme {"]
    for mode_name, mode in (("light", light), ("dark", dark)):
        lines.append(f"    static let {mode_name} = SchemeColors(")
        for i, k in enumerate(keys):
            sep = "," if i < len(keys) - 1 else ""
            lines.append(f"        {k}: {swift_color(mode[k])}{sep}")
        lines.append("    )" + ("\n" if mode_name == "light" else ""))
    lines.append("}")
    return "\n".join(lines)


