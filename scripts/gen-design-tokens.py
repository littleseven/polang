def pascal(name):
    return name[0].upper() + name[1:]


def gen_kotlin_color(tokens):
    scheme = tokens["colorScheme"]
    lines = [kt_header("import androidx.compose.ui.graphics.Color\n")]
    lines.append("// ── M3 baseline 配色（colorScheme.light/dark）──────────────────────────────────")
    lines.append("// 注：ErrorLight 已按 SSOT 修正为 M3 标准 #B3261E（旧值 0xB32610 有 alpha=00 透明 bug）。")
    for mode, suffix in (("light", "Light"), ("dark", "Dark")):
        lines.append("")
        for key, hexv in scheme[mode].items():
            lines.append(f"val {pascal(key)}{suffix} = {kotlin_color(hexv)}")
    lines += ["", "// ── 功能色（color 组，不随主题切换）。引用方式：MaterialTheme.appColors.focusRing ──────────"]
    color_group = {k: v for k, v in tokens["color"].items() if not k.startswith("_")}
    # 顶层 val 命名历史约定：vibrant* 无 Color 后缀，其余有
    top_names = {}
    for key, hexv in color_group.items():
        top = pascal(key) if key.startswith("vibrant") else pascal(key) + "Color"
        top_names[key] = top
        lines.append(f"val {top} = {kotlin_color(hexv)}")
    lines += ["", "/** 功能色集合，通过 [MaterialTheme.appColors] 访问。 */", "object AppColors {"]
    for key in color_group:
        lines.append(f"    val {key} = {top_names[key]}")
    lines.append("}")
    return "\n".join(lines) + "\n"


